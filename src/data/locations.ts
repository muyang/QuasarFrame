export const locations: Location[] = locationDetails.map((location) => {
  const photo = locationMedia[location.id];
  return { ...location, heroImage: photo?.imageUrl ?? '', photos: photo ? [photo] : [] };
});

export function getLocationById(id: string): Location | undefined {
  return locations.find((l) => l.id === id);
}

export function getLocationsByScenery(sceneryType: string): Location[] {
  return locations.filter((l) => l.sceneryTags.includes(sceneryType as never));
}
